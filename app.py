import os
import pickle
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import streamlit as st

# Konfigurasi Halaman
st.set_page_config(page_title="Mall Customer Segmentation", layout="wide")

st.title("Aplikasi Segmentasi Pelanggan Mall (K-Means)")
st.write(
    "Aplikasi web untuk mengelompokkan pelanggan berdasarkan Pendapatan Tahunan dan Skor Pengeluaran."
)

# Deteksi direktori dasar
BASE_DIR = (
    os.path.dirname(os.path.abspath(__file__))
    if "__file__" in globals()
    else os.getcwd()
)


# Memuat Model secara aman
@st.cache_resource
def load_model():
    # Cek lokasi file pkl
    path1 = os.path.join(BASE_DIR, "model_kmeans.pkl")
    path2 = "model_kmeans.pkl"
    chosen_path = path1 if os.path.exists(path1) else path2

    with open(chosen_path, "rb") as file:
        return pickle.load(file)


kmeans = load_model()


# Memuat Data secara aman
@st.cache_data
def load_data():
    # Cek apakah ada di folder data/ atau di folder utama
    path_in_folder = os.path.join(BASE_DIR, "data", "Mall_Customers.csv")
    path_root = os.path.join(BASE_DIR, "Mall_Customers.csv")

    if os.path.exists(path_in_folder):
      return pd.read_csv(path_in_folder)
    elif os.path.exists(path_root):
      return pd.read_csv(path_root)
    else:
      return pd.read_csv("Mall_Customers.csv")


df = load_data()
X = df.iloc[:, [3, 4]].values

# Label Karakteristik Tiap Klaster
cluster_labels = {
    0: ("Standar", "Pendapatan sedang dan pengeluaran sedang."),
    1: (
        "Boros / Target Promosi",
        "Pendapatan tinggi dan pengeluaran tinggi. Target utama kampanye produk"
        " baru.",
    ),
    2: ("Sultan", "Pendapatan rendah tetapi pengeluaran tinggi."),
    3: (
        "Hemat",
        "Pendapatan tinggi namun pengeluaran rendah. Perlu insentif diskon.",
    ),
    4: ("Prioritas Rendah", "Pendapatan rendah dan pengeluaran rendah."),
}

# Sidebar Input Pengguna
st.sidebar.header("Input Data Pelanggan Baru")
income_input = st.sidebar.slider(
    "Annual Income (k$)", min_value=15, max_value=150, value=60, step=1
)
score_input = st.sidebar.slider(
    "Spending Score (1-100)", min_value=1, max_value=100, value=50, step=1
)

# Tombol Prediksi
if st.sidebar.button("Prediksi Klaster"):
  user_data = np.array([[income_input, score_input]])
  prediction = kmeans.predict(user_data)[0]
  nama_klaster, deskripsi = cluster_labels[prediction]

  col1, col2 = st.columns([1, 2])

  with col1:
    st.subheader("Hasil Segmentasi")
    st.success(f"Masuk ke dalam **Cluster {prediction + 1}: {nama_klaster}**")
    st.write(f"**Karakteristik:** {deskripsi}")
    st.metric(label="Annual Income", value=f"${income_input}k")
    st.metric(label="Spending Score", value=score_input)

  with col2:
    st.subheader("Posisi Pelanggan pada Sebaran Data")
    y_kmeans = kmeans.predict(X)

    fig, ax = plt.subplots(figsize=(8, 5))
    colors = ["red", "blue", "green", "cyan", "magenta"]
    for i in range(5):
      ax.scatter(
          X[y_kmeans == i, 0],
          X[y_kmeans == i, 1],
          s=40,
          c=colors[i],
          label=f"Cluster {i+1}",
      )

    # Titik Centroid
    ax.scatter(
        kmeans.cluster_centers_[:, 0],
        kmeans.cluster_centers_[:, 1],
        s=150,
        c="yellow",
        marker="X",
        label="Centroids",
    )

    # Titik Input Pengguna
    ax.scatter(
        income_input,
        score_input,
        s=200,
        c="black",
        marker="*",
        label="Input Pelanggan",
    )

    ax.set_title("Visualisasi Klaster")
    ax.set_xlabel("Annual Income (k$)")
    ax.set_ylabel("Spending Score (1-100)")
    ax.legend()
    ax.grid(True)
    st.pyplot(fig)
else:
  st.info(
      "Silakan atur nilai pada panel di sebelah kiri, lalu klik tombol"
      " **Prediksi Klaster**."
  )